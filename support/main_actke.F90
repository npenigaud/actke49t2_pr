REAL(KIND=JPRB)             ,POINTER        :: PFECTI(:,:,:)
REAL(KIND=JPRB)             ,POINTER        :: PECT1(:,:,:)
REAL(KIND=JPRB)             ,POINTER        :: PTPRDY(:,:,:)
REAL(KIND=JPRB)             ,POINTER        :: PEDR(:,:,:)

#include "actke.intfb.h"
#include "actke_openacc.intfb.h"

CHARACTER (LEN=128) :: CLOUT
